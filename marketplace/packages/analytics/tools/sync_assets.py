#!/usr/bin/env python3
"""Keep the package's generated copies identical to their sources.

A dashboard page may load exactly one script, so ``content/web/page.js`` is
assembled from ``content/web/src/replay-player.js`` and
``content/web/src/page.ui.js``. The instance's own pages load the tracking SDK
from the site's asset tree, so ``www/public/analytics-sdk.js`` is a copy of
``content/sdk/analytics-sdk.js``. Edit the sources, then run this tool;
``--check`` fails when a copy has drifted (the test suite runs it).
"""

from pathlib import Path
import sys


PACKAGE = Path(__file__).resolve().parents[1]
REPOSITORY = PACKAGE.parents[2]
WEB = PACKAGE / "content" / "web"
PAGE_PARTS = ("replay-player.js", "page.ui.js")
PAGE = WEB / "page.js"
SDK = PACKAGE / "content" / "sdk" / "analytics-sdk.js"
SITE_SDK = REPOSITORY / "www" / "public" / "analytics-sdk.js"
BANNER = (
    "// GENERATED by marketplace/packages/analytics/tools/sync_assets.py. Edit\n"
    "// content/web/src/*.js, then run the tool.\n"
)
SITE_BANNER = (
    "// GENERATED copy of marketplace/packages/analytics/content/sdk/"
    "analytics-sdk.js.\n// Edit that file, then run the package's "
    "tools/sync_assets.py.\n"
)


def _marker(name, edge):
    return "// ==== %s %s ====\n" % (edge, name)


def page_source():
    parts = [BANNER]
    for name in PAGE_PARTS:
        parts += [_marker(name, "BEGIN"),
                  (WEB / "src" / name).read_text(encoding="utf-8"),
                  _marker(name, "END")]
    return "\n".join(parts)


def targets():
    wanted = {PAGE: page_source()}
    if SITE_SDK.parent.is_dir():
        wanted[SITE_SDK] = SITE_BANNER + SDK.read_text(encoding="utf-8")
    return wanted


def main(argv):
    check = "--check" in argv
    drifted = []
    for path, source in targets().items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == source:
            continue
        drifted.append(path)
        if not check:
            path.write_text(source, encoding="utf-8")
    for path in drifted:
        print(("out of date: " if check else "wrote ")
              + str(path.relative_to(REPOSITORY)))
    return 1 if check and drifted else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
