#!/usr/bin/env python3
"""Keep every copy of the vault's cryptography identical to the source.

content/crypto/vault-crypto.js and vault-client.js are the only places the
code is edited. A dashboard page may load exactly one script, so page.js is
assembled from those two files plus content/web/page.ui.js; the browser
extension package ships its own copies because a package is installed on its
own. ``--check`` fails when any copy has drifted (the test suite runs it).
"""

from pathlib import Path
import sys


PACKAGE = Path(__file__).resolve().parents[1]
CRYPTO = PACKAGE / "content" / "crypto"
SHARED = ("vault-crypto.js", "vault-client.js")
PAGE_UI = PACKAGE / "content" / "web" / "page.ui.js"
PAGE = PACKAGE / "content" / "web" / "page.js"
EXTENSION = PACKAGE.parent / "browser-extension" / "content" / "extension"
BANNER = (
    "// GENERATED by marketplace/packages/vault/tools/sync_crypto.py. Edit\n"
    "// content/crypto/*.js and content/web/page.ui.js, then run the tool.\n"
)


def _marker(name, edge):
    return "// ==== %s %s ====\n" % (edge, name)


def page_source():
    parts = [BANNER]
    for name in SHARED:
        parts += [_marker(name, "BEGIN"), (CRYPTO / name).read_text(encoding="utf-8"),
                  _marker(name, "END")]
    parts.append(PAGE_UI.read_text(encoding="utf-8"))
    return "\n".join(parts)


def targets():
    wanted = {PAGE: page_source()}
    if EXTENSION.is_dir():
        for name in SHARED:
            wanted[EXTENSION / name] = (CRYPTO / name).read_text(encoding="utf-8")
    return wanted


def main(argv):
    check = "--check" in argv
    drifted = []
    for path, source in targets().items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == source:
            continue
        drifted.append(path)
        if not check:
            path.write_text(source, encoding="utf-8")
    for path in drifted:
        print(("out of date: " if check else "wrote ") + str(path.relative_to(PACKAGE.parent)))
    return 1 if check and drifted else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
