#!/usr/bin/env python3
"""Generate the World's package module from catalogued world entrypoints.

Every catalogued package with a ``world`` entrypoint becomes one entry in
``BUNDLED_WORLD_PACKAGES``. The entry always carries the manifest summary the
World's Marketplace tab shows, but only a package that ships installed
(``install.default`` true, the default) is imported statically. A package that
ships switched off keeps its code behind a ``load()`` thunk — a dynamic
``import()`` — so an uninstalled district never joins the World's initial
module graph or its byte budget.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import sys

from marketplace_lib import (
    MarketplaceError, environment_plugin_selection, load_catalog, safe_relative_path,
    selected_manifest_entries,
)


def _js_string(value: object) -> str:
    return json.dumps(str(value or ""), ensure_ascii=False)


def generate(catalog_path: Path, output: Path) -> str:
    catalog = load_catalog(catalog_path)
    imports = []
    entries = []
    selection = environment_plugin_selection(catalog)
    for _, manifest in selected_manifest_entries(catalog, selection):
        entrypoint = str((manifest.get("entrypoints") or {}).get("world") or "")
        if not entrypoint:
            continue
        relative = safe_relative_path(entrypoint, "world entrypoint")
        source = catalog.root / "packages" / manifest["id"] / relative
        if not source.is_file():
            raise MarketplaceError(
                f"package {manifest['id']} world entrypoint does not exist"
            )
        install = manifest.get("install") or {}
        installed_by_default = install.get("default", True) is not False
        name = "package_" + re.sub(r"[^A-Za-z0-9_]", "_", manifest["id"])
        import_path = Path(os.path.relpath(source.resolve(), output.parent.resolve()))
        specifier = import_path.as_posix()
        summary = "\n".join(
            [
                "    manifest: Object.freeze({",
                f"      id: {_js_string(manifest['id'])},",
                f"      label: {_js_string(manifest.get('name'))},",
                f"      category: {_js_string(manifest.get('category') or 'Packages')},",
                f"      summary: {_js_string(manifest.get('summary'))},",
                "    }),",
                f"    installedByDefault: {'true' if installed_by_default else 'false'},",
            ]
        )
        if installed_by_default:
            imports.append(f'import * as {name} from "{specifier}";')
            entries.append(
                "\n".join(
                    [
                        "  Object.freeze({",
                        summary,
                        f"    module: {name},",
                        "  }),",
                    ]
                )
            )
        else:
            entries.append(
                "\n".join(
                    [
                        "  {",
                        summary,
                        "    module: null,",
                        f'    load: () => import("{specifier}"),',
                        "  },",
                    ]
                )
            )
    return "\n".join(
        [
            "// Generated by marketplace/tools/generate_world_packages.py; do not edit.",
            *imports,
            "",
            "export const BUNDLED_WORLD_PACKAGES = Object.freeze([",
            *entries,
            "]);",
            "",
        ]
    )


def main(arguments: list[str]) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--catalog", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args(arguments)
    try:
        content = generate(options.catalog, options.output)
    except MarketplaceError as error:
        print(f"generate_world_packages: {error}", file=sys.stderr)
        return 2
    current = options.output.read_text(encoding="utf-8") if options.output.exists() else ""
    if options.check:
        if current != content:
            print(f"{options.output} is out of date", file=sys.stderr)
            return 1
        return 0
    if current != content:
        options.output.parent.mkdir(parents=True, exist_ok=True)
        options.output.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
