#!/usr/bin/env python3
from __future__ import annotations

import argparse
import ipaddress
import json
import os
import subprocess
import sys
from pathlib import Path

MAX_AGENTS = 1000
MAX_AGENT = 256
MAX_NETWORKS = 20000
NETWORKS_PER_LINE = 64
EXEMPT = "not path /health /readyz /api/fleet/*"
CHECK_SNIPPET = "request_policy_check"
GOOGLE = "(?i)google"
WELCOME = "(?i)chatgpt-user|oai-searchbot"
USER_AGENT = "{http.request.header.User-Agent}"
REGEX_SPECIAL = frozenset("\\.+*?()|[]{}^$")
MARKER = "# Generated by fmnext-request-rules from request_block_rules. Do not edit."
RELOAD = ("systemctl", "try-reload-or-restart", "caddy.service")


class RulesError(ValueError):
    pass


def agent_literal(keyword: str) -> str:
    out = []
    for ch in keyword:
        if ch in REGEX_SPECIAL:
            out.append("\\" + ch)
        elif ch == "`":
            out.append("\\x60")
        else:
            out.append(ch)
    return "".join(out)


def agents(values):
    result = set()
    skipped = 0
    for value in values or ():
        if not isinstance(value, str):
            skipped += 1
            continue
        text = value.strip().lower()
        if not text or len(text) > MAX_AGENT or any(
                not " " <= ch <= "~" for ch in text):
            skipped += 1
            continue
        result.add(text)
    if len(result) > MAX_AGENTS:
        raise RulesError("more than %d user-agent keywords" % MAX_AGENTS)
    return sorted(result), skipped


def networks(networks_value, ranges_value):
    found = []
    skipped = 0
    for value in networks_value or ():
        try:
            found.append(ipaddress.ip_network(str(value), strict=False))
        except ValueError:
            skipped += 1
    for pair in ranges_value or ():
        try:
            start_text, end_text = pair
            start = ipaddress.ip_address(str(start_text))
            end = ipaddress.ip_address(str(end_text))
        except (TypeError, ValueError):
            skipped += 1
            continue
        if start.version != end.version or start > end:
            skipped += 1
            continue
        found.extend(ipaddress.summarize_address_range(start, end))
    collapsed = []
    for version in (4, 6):
        collapsed.extend(ipaddress.collapse_addresses(
            n for n in found if n.version == version))
    if len(collapsed) > MAX_NETWORKS:
        raise RulesError("more than %d blocked networks" % MAX_NETWORKS)
    return [str(n) for n in collapsed], skipped


def parse(text: str):
    try:
        data = json.loads(text)
    except ValueError as error:
        raise RulesError("rules file is not JSON: %s" % error) from None
    if not isinstance(data, dict) or data.get("version") != 1:
        raise RulesError("rules file has no version 1 object")
    keywords, skipped_agents = agents(data.get("agents"))
    nets, skipped_networks = networks(data.get("networks"), data.get("ranges"))
    return keywords, nets, skipped_agents + skipped_networks


def render(keywords, nets) -> str:
    out = [MARKER]
    if nets:
        out += ["@request_rules_address {", "\t" + EXEMPT]
        for index in range(0, len(nets), NETWORKS_PER_LINE):
            out.append("\tremote_ip " + " ".join(
                nets[index:index + NETWORKS_PER_LINE]))
        out += ["}", "handle @request_rules_address {",
                "\theader Cache-Control no-store",
                "\trespond \"Forbidden\" 403", "}"]
    if keywords:
        pattern = "`(?i)(?:%s)`" % "|".join(agent_literal(k) for k in keywords)
        out += ["@request_rules_agent {", "\t" + EXEMPT,
                "\theader_regexp request_rules_agent User-Agent " + pattern,
                "\tnot vars_regexp %s `%s`" % (USER_AGENT, GOOGLE),
                "\tnot vars_regexp %s `%s`" % (USER_AGENT, WELCOME), "}",
                "handle @request_rules_agent {",
                "\theader Cache-Control no-store",
                "\trespond \"Forbidden\" 403", "}",
                "@request_rules_crawler {", "\t" + EXEMPT,
                "\theader_regexp request_rules_crawler User-Agent " + pattern,
                "\tvars_regexp request_rules_google %s `%s`" % (USER_AGENT, GOOGLE),
                "\tnot vars_regexp %s `%s`" % (USER_AGENT, WELCOME),
                "}",
                "import %s @request_rules_crawler" % CHECK_SNIPPET]
    return "\n".join(out) + "\n"


def write_if_changed(path: Path, text: str) -> bool:
    try:
        if path.read_text(encoding="utf-8") == text:
            return False
    except OSError:
        pass
    path.parent.mkdir(mode=0o755, parents=True, exist_ok=True)
    temporary = path.with_name(".%s.tmp" % path.name)
    temporary.write_text(text, encoding="utf-8")
    os.chmod(temporary, 0o644)
    os.replace(temporary, path)
    return True


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Render request_block_rules into a Caddy include.")
    parser.add_argument("--rules", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--reload", action="store_true")
    args = parser.parse_args(argv)
    source = Path(args.rules)
    try:
        text = source.read_text(encoding="utf-8")
    except FileNotFoundError:
        text = None
    except OSError as error:
        print("request-rules: cannot read %s: %s" % (source, error),
              file=sys.stderr)
        return 1
    try:
        keywords, nets, skipped = parse(text) if text is not None else ([], [], 0)
    except RulesError as error:
        print("request-rules: %s; keeping %s" % (error, args.out),
              file=sys.stderr)
        return 1
    changed = write_if_changed(Path(args.out), render(keywords, nets))
    print("request-rules: %d keywords, %d networks, %d skipped, %s" % (
        len(keywords), len(nets), skipped,
        "updated" if changed else "unchanged"))
    if changed and args.reload:
        return subprocess.run(RELOAD, check=False).returncode
    return 0


if __name__ == "__main__":
    sys.exit(main())
