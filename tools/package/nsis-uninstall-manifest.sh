#!/usr/bin/env bash
# Write the NSIS uninstall list for a Windows payload directory (issue #727).
#
#   tools/package/nsis-uninstall-manifest.sh <payload-dir> <out.nsh>
#
# The uninstaller removes exactly what the installer copied: one `Delete` per
# payload file, then one non-recursive `RMDir` per payload directory, deepest
# first. A directory still holding anything the installer did not put there
# (user data such as %LOCALAPPDATA%\ForkMesh\ForkMesh, caches, logs) is
# therefore left in place. Never emit `RMDir /r`.
set -euo pipefail

payload="${1:?payload directory}"
out="${2:?output .nsh}"
[ -d "$payload" ] || { echo "not a directory: $payload" >&2; exit 1; }

nsis_path() {
  # Payload-relative POSIX path -> escaped NSIS "$INSTDIR\..." literal.
  local rel="$1"
  case "$rel" in
    *$'\n'* | *$'\r'*) echo "refusing a payload name with a line break: $rel" >&2; exit 1 ;;
  esac
  rel="${rel//\$/\$\$}"
  rel="${rel//\"/\$\\\"}"
  rel="${rel//\//\\}"
  printf '$INSTDIR\\%s' "$rel"
}

tmp="$(mktemp "${out}.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
{
  echo "; Generated by tools/package/nsis-uninstall-manifest.sh -- do not edit."
  (cd "$payload" && find . -mindepth 1 \( -type f -o -type l \) -printf '%P\n' | LC_ALL=C sort) |
    while IFS= read -r rel; do
      printf '  Delete "%s"\n' "$(nsis_path "$rel")"
    done
  (cd "$payload" && find . -mindepth 1 -type d -printf '%d\t%P\n' | LC_ALL=C sort -t$'\t' -k1,1nr -k2,2r) |
    while IFS=$'\t' read -r _depth rel; do
      printf '  RMDir "%s"\n' "$(nsis_path "$rel")"
    done
} > "$tmp"
if grep -q 'RMDir /r' "$tmp"; then
  echo "internal error: recursive RMDir in the uninstall manifest" >&2
  exit 1
fi
mv "$tmp" "$out"
trap - EXIT
