#!/usr/bin/env python3
"""Regenerate the desktop's embedded coding-agent header from its source."""

from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tools" / "forkmesh_coding_agent.py"
TARGET = ROOT / "desktop" / "src" / "CloudflareAgentScript.h"


def render(source: str) -> str:
    """Wrap Python source in a collision-resistant C++ raw string."""

    # Keep the historical delimiter: release tests and downstream packagers
    # extract this literal to exercise exactly what the desktop will run.
    delimiter = "PYAGENT"
    if ")" + delimiter + '"' in source:
        raise ValueError("raw-string delimiter appears in agent source")
    return (
        "#pragma once\n\n"
        "// Generated by tools/sync_coding_agent_header.py. Do not edit by hand.\n"
        "// The canonical, independently testable source is tools/forkmesh_coding_agent.py.\n\n"
        "#include <QString>\n\n"
        "inline QString forkmeshCloudflareAgentScript()\n{\n"
        "    return QString::fromUtf8(R\"" + delimiter + "(" + source
        + ")" + delimiter + "\");\n}\n"
    )


def main() -> int:
    TARGET.write_text(render(SOURCE.read_text(encoding="utf-8")), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
