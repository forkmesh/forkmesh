def test_gateway_health_and_router_protocols_are_key_pinned(identity):
    health = gateway.ExternalHealthSigner(
        helper_command(identity, "health-sign"),
        identity["public"]["nodePublicKey"],
    )
    message = "forkmesh-https-health-v1\nmirror-two\n0123456789abcdef\n1784840000000"
    health_signature = health.sign(message)
    assert len(base64.urlsafe_b64decode(health_signature + "==")) == 64

    verifier = gateway.ExternalCapabilityVerifier(
        helper_command(identity, "capability-verify"),
        identity["public"]["routerPublicKey"],
    )
    capability = (
        "forkmesh-masked-proxy-v1\nmirror-two\nGET\n"
        "/v1/repositories/forkmesh/forkmesh/git-info-refs\n"
        + hashlib.sha256(b"").hexdigest()
        + "\nrequest-id-123456\n1784840000000"
    )
    signature = b64url(identity["router_key"].sign(capability.encode("utf-8")))
    assert verifier.verify(capability, signature)
    wrong_key = Ed25519PrivateKey.generate()
    assert not verifier.verify(
        capability, b64url(wrong_key.sign(capability.encode("utf-8")))
    )


def _run(command, cwd=None):
    return subprocess.run(
        command,
        cwd=cwd,
        check=True,
        capture_output=True,
        text=True,
        env={
            "PATH": os.environ.get("PATH", ""),
            "LANG": "C",
            "LC_ALL": "C",
        },
    ).stdout.strip()


def make_bare_repository(tmp_path):
    source = tmp_path / "source"
    bare = tmp_path / "source.git"
    source.mkdir()
    _run(["git", "init", "-b", "main"], source)
    _run(["git", "config", "user.name", "ForkMesh test"], source)
    _run(["git", "config", "user.email", "test@example.invalid"], source)
    (source / "README.md").write_text("headless mirror\n", encoding="utf-8")
    _run(["git", "add", "README.md"], source)
    _run(["git", "commit", "-m", "initial"], source)
    _run(["git", "clone", "--bare", str(source), str(bare)])
    return bare


def test_seal_and_materialize_round_trip(identity, tmp_path):
    bare = make_bare_repository(tmp_path)
    encrypted = tmp_path / "forkmesh.age"
    metadata = helper.seal_repository(
        identity["state_dir"],
        {
            "schemaVersion": 1,
            "type": "forkmesh.repository-archive-seal",
            "sourceRepository": str(bare),
            "ciphertextPath": str(encrypted),
        },
        age_program=str(identity["age"]),
    )
    assert encrypted.read_bytes().startswith(helper.AGE_NATIVE_HEADER)
    assert stat.S_IMODE(encrypted.stat().st_mode) == 0o600
    assert metadata == {
        "ok": True,
        "scheme": "age-encrypted-tar-v1",
        "ciphertextSha256": hashlib.sha256(encrypted.read_bytes()).hexdigest(),
        "ciphertextBytes": encrypted.stat().st_size,
        "keyReference": identity["public"]["ageKeyReference"],
        "expectedRefsSha256": gateway.refs_sha256(bare),
    }
    destination = tmp_path / "runtime"
    destination.mkdir(mode=0o700)
    response = helper.materialize_repository(
        identity["state_dir"],
        {
            "schemaVersion": 1,
            "type": "forkmesh.repository-archive-materialize",
            "scheme": metadata["scheme"],
            "ciphertextPath": str(encrypted),
            "ciphertextSha256": metadata["ciphertextSha256"],
            "keyReference": metadata["keyReference"],
            "destination": str(destination),
        },
        age_program=str(identity["age"]),
    )
    assert response == {"ok": True, "repositoryPath": "repository.git"}
    materialized = destination / "repository.git"
    assert (
        _run(
            ["git", "--git-dir", str(materialized), "rev-parse", "--is-bare-repository"]
        )
        == "true"
    )
    assert gateway.refs_sha256(materialized) == metadata["expectedRefsSha256"]


def _malicious_tar(kind):
    stream = io.BytesIO()
    with tarfile.open(fileobj=stream, mode="w") as archive:
        root = tarfile.TarInfo("repository.git")
        root.type = tarfile.DIRTYPE
        archive.addfile(root)
        if kind == "traversal":
            item = tarfile.TarInfo("../escaped")
            item.size = 1
            archive.addfile(item, io.BytesIO(b"x"))
        elif kind == "symlink":
            item = tarfile.TarInfo("repository.git/HEAD")
            item.type = tarfile.SYMTYPE
            item.linkname = "/etc/passwd"
            archive.addfile(item)
        else:
            item = tarfile.TarInfo("repository.git/device")
            item.type = tarfile.CHRTYPE
            item.devmajor = 1
            item.devminor = 3
            archive.addfile(item)
    return stream.getvalue()


@pytest.mark.parametrize("kind", ["traversal", "symlink", "device"])
def test_materializer_rejects_traversal_links_and_devices(identity, tmp_path, kind):
    encrypted = tmp_path / f"{kind}.age"
    encrypted.write_bytes(helper.AGE_NATIVE_HEADER + _malicious_tar(kind))
    destination = tmp_path / f"runtime-{kind}"
    destination.mkdir(mode=0o700)
    with pytest.raises(helper.HelperError, match="archive"):
        helper.materialize_repository(
            identity["state_dir"],
            {
                "schemaVersion": 1,
                "type": "forkmesh.repository-archive-materialize",
                "scheme": "age-encrypted-tar-v1",
                "ciphertextPath": str(encrypted),
                "ciphertextSha256": hashlib.sha256(encrypted.read_bytes()).hexdigest(),
                "keyReference": identity["public"]["ageKeyReference"],
                "destination": str(destination),
            },
            age_program=str(identity["age"]),
        )
    assert list(destination.iterdir()) == []
    assert not (tmp_path / "escaped").exists()


def test_operator_only_payloads_match_worker_canonicals(identity):
    node_private = helper._load_node_key(identity["state_dir"])
    node_public = node_private.public_key()
    reclaim = helper.sign_account_reclaim(
        identity["state_dir"],
        {
            "schemaVersion": 1,
            "type": "forkmesh.account-reclaim-signing",
            "nodeName": "mirror-two",
            "linkCode": "123456",
        },
        clock_ms=lambda: 1784840000000,
    )
    reclaim_payload = (
        "forkmesh-reclaim-node-v1\nmirror-two\n"
        + identity["public"]["nodePublicKey"]
        + "\n123456\n1784840000000"
    ).encode()
    node_public.verify(base64.urlsafe_b64decode(reclaim["sig"] + "=="), reclaim_payload)

    registration = helper.sign_endpoint_registration(
        identity["state_dir"],
        {
            "schemaVersion": 1,
            "type": "forkmesh.https-endpoint-registration-signing",
            "node": "mirror-two",
            "baseUrl": "https://mirror2.forkmesh.com",
        },
        clock_ms=lambda: 1784840000001,
    )
    registration_payload = (
        "forkmesh-https-endpoint-v1\nmirror-two\n"
        "https://mirror2.forkmesh.com\n"
        + identity["public"]["nodePublicKey"]
        + "\n1784840000001"
    ).encode()
    node_public.verify(
        base64.urlsafe_b64decode(registration["signature"] + "=="),
        registration_payload,
    )
    direct_registration = helper.sign_endpoint_registration(
        identity["state_dir"],
        {
            "schemaVersion": 1,
            "type": "forkmesh.https-endpoint-registration-signing",
            "node": "mirror-two",
            "baseUrl": "https://mirror2.forkmesh.com",
            "mirrorUrl": "https://mirror2.forkmesh.com",
        },
        clock_ms=lambda: 1784840000002,
    )
    direct_payload = (
        "forkmesh-https-endpoint-v2\nmirror-two\n"
        "https://mirror2.forkmesh.com\n"
        "https://mirror2.forkmesh.com\n"
        + identity["public"]["nodePublicKey"]
        + "\n1784840000002"
    ).encode()
    node_public.verify(
        base64.urlsafe_b64decode(direct_registration["signature"] + "=="),
        direct_payload,
    )

    deletion = helper.sign_repository_delete(
        identity["state_dir"],
        {
            "schemaVersion": 1,
            "type": "forkmesh.repository-delete-signing",
            "owner": "mirror-two",
            "name": "codeberg-demo",
            "timestamp": 1784840000001,
        },
        clock_ms=lambda: 1784840000001,
    )
    deletion_payload = (
        "forkmesh-catalog-delete-v1\n"
        "mirror-two\ncodeberg-demo\n1784840000001"
    ).encode()
    node_public.verify(
        base64.urlsafe_b64decode(deletion["signature"] + "=="),
        deletion_payload,
    )

    state_hash = hashlib.sha256(b"refs").hexdigest()
    record = helper.sign_catalog_v2(
        identity["state_dir"],
        {
            "schemaVersion": 1,
            "type": "forkmesh.catalog-v2-publication-signing",
            "record": {
                "owner": "forkmesh",
                "name": "forkmesh",
                "visibility": "public",
                "description": "Living code city \N{SNOWMAN}",
                "updatedAt": "1784840000002",
                "stateHash": state_hash,
                "cpuPercent": 126,
                "memUsedBytes": 900,
                "memTotalBytes": 800,
                "diskUsedBytes": 300,
                "diskTotalBytes": 1000,
                "actionsEnabled": True,
                "actionsState": "running",
            },
        },
    )
    # The helper and Worker share the same integer/null catalog-v2 shape:
    # opt-in metrics are bounded before signing and byte-pair usage cannot
    # exceed its total.
    assert record["cpuPercent"] == 100
    assert (record["memUsedBytes"], record["memTotalBytes"]) == (800, 800)
    assert (record["diskUsedBytes"], record["diskTotalBytes"]) == (300, 1000)
    assert record["actionsEnabled"] is True
    assert record["actionsState"] == "running"
    state_payload = (
        "forkmesh-repostate-v1\nforkmesh\nforkmesh\n" + state_hash + "\n1784840000002"
    ).encode()
    node_public.verify(
        base64.urlsafe_b64decode(record["stateSig"] + "=="), state_payload
    )
    normalized = dict(record)
    catalog_signature = normalized.pop("catalogSig")
    assert normalized.pop("catalogSigVersion") == 2
    # Worker catalog-v2 verification removes this retained legacy-v1 field.
    assert normalized.pop("signature") == ""
    record_hash = hashlib.sha256(
        json.dumps(normalized, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()
    node_public.verify(
        base64.urlsafe_b64decode(catalog_signature + "=="),
        ("forkmesh-catalog-v2\n" + record_hash).encode(),
    )
    tampered = dict(normalized)
    tampered["actionsState"] = "enabled"
    tampered_hash = hashlib.sha256(
        json.dumps(tampered, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()
    with pytest.raises(InvalidSignature):
        node_public.verify(
            base64.urlsafe_b64decode(catalog_signature + "=="),
            ("forkmesh-catalog-v2\n" + tampered_hash).encode(),
        )

    unreported = helper._normalized_public_catalog(
        {
            "owner": "forkmesh",
            "name": "forkmesh",
            "visibility": "public",
            "updatedAt": "1784840000002",
            "stateHash": state_hash,
        },
        identity["public"]["nodePublicKey"],
        now_ms=1784840000002,
    )
    assert not {
        "cpuPercent",
        "memUsedBytes",
        "memTotalBytes",
        "diskUsedBytes",
        "diskTotalBytes",
        "actionsEnabled",
        "actionsState",
        "cloneServedAt",
        "cloneServedAgent",
        "websiteServedAt",
        "websiteServedAgent",
    }.intersection(unreported)

    # Last-served stamps: signed when the gateway reported one, and only ever
    # as a bounded client class. A raw User-Agent (a request fingerprint) and a
    # non-positive stamp are dropped, matching the Worker's normalizer exactly.
    served = helper._normalized_public_catalog(
        {
            "owner": "forkmesh",
            "name": "forkmesh",
            "visibility": "public",
            "updatedAt": "1784840000002",
            "stateHash": state_hash,
            "cloneServedAt": "1784839000000",
            "cloneServedAgent": "git-client",
            "websiteServedAt": "0",
            "websiteServedAgent": "Mozilla/5.0 (X11)",
        },
        identity["public"]["nodePublicKey"],
        now_ms=1784840000002,
    )
    assert served["cloneServedAt"] == "1784839000000"
    assert served["cloneServedAgent"] == "git-client"
    assert "websiteServedAt" not in served
    assert "websiteServedAgent" not in served


