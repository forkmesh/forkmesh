def test_loopback_detection_requires_a_completed_round_trip():
    module = _module()

    host = module.ConformanceSuite._loopback_host()

    if host is None:
        # Nothing to prove: the runner has no usable loopback at all and the
        # suite will select the socketless oracle.
        return
    assert host in ("127.0.0.1", "::1")
    # A bind alone is not the claim being made. The reported host must accept
    # a real connection, or --transport auto would hang instead of degrading.
    with module._LoopbackHTTPServer(host, module._QuietHandler) as server:
        thread = threading.Thread(target=server.serve_forever, daemon=True)
        thread.start()
        try:
            with socket.create_connection(
                (host, server.server_address[1]), timeout=2
            ):
                pass
        finally:
            server.shutdown()
            thread.join(timeout=5)


