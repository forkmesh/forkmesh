@pytest.mark.parametrize("protocol_version", ["0", "2"])
def test_stock_git_probe_preserves_ids_rejects_stale_lease_and_detects_corruption(
    protocol_version,
):
    module = _module()
    matrix = module.load_matrix()
    report = module.run_conformance(
        matrix,
        git_executable="git",
        protocol_version=protocol_version,
        client_label="pytest-system-git",
        # Pinned to the socketless oracle so this contract never depends on
        # the runner's loopback. AF_INET is not denied here; a bind succeeds
        # and the traffic is dropped, which is what _loopback_host detects.
        # The oracle still executes stock upload-pack/receive-pack for every
        # ref and object operation.
        transport_mode="file",
    )

    assert report["schema"] == "forkmesh-git-conformance-report-v1"
    assert report["summary"] == {
        "status": "pass",
        "pass": 15,
        "fail": 0,
        "notRun": 0,
        "failure": "",
        "compatibility": {
            "passedOperationPathCells": 39,
            "totalOperationPathCells": 39,
            "passRate": 1.0,
        },
    }
    rows = {row["id"]: row for row in report["operations"]}
    assert set(rows) == module.REQUIRED_OPERATIONS
    assert all(row["status"] == "pass" for row in rows.values())
    if protocol_version == "0":
        assert "expected safe protocol-v0 lazy-fetch rejection" in rows[
            "partial-clone"
        ]["detail"]
    else:
        assert rows["partial-clone"]["detail"] == (
            "stock Git behavior and integrity assertions passed"
        )
    assert rows["force-with-lease"]["paths"] == ["direct"]
    assert rows["integrity"]["paths"] == [
        "direct", "relay", "mirror-failover"
    ]
    assert len(report["integrity"]["signedCommit"]) == 40
    assert len(report["integrity"]["refsSha256"]) == 64
    assert all(
        report["integrity"][field] is False
        for field in (
            "temporaryPathsIncluded",
            "repositoryContentsIncluded",
            "credentialsIncluded",
            "clientAddressesIncluded",
        )
    )
    serialized = json.dumps(report)
    assert not re.search(
        r"[/\\\\]forkmesh-git-conformance-[^\" ]*[/\\\\]", serialized
    )
    assert "file://" not in serialized
    assert "127.0.0.1" not in serialized
    assert "::1" not in serialized


