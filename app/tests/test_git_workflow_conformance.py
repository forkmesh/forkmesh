def test_failed_run_names_the_probe_and_reason_on_stderr(monkeypatch, tmp_path, capsys):
    module = _module()
    matrix = module.load_matrix()
    rows = [
        {"id": operation["probe"], "status": "pass", "paths": [], "durationMs": 1,
         "detail": "stock Git behavior and integrity assertions passed"}
        for operation in matrix["operations"]
    ]
    reason = "Git command could not run: git clone <fixture-url>/project.git: timed out after 90 seconds"
    rows[-2].update({"status": "fail", "detail": reason})
    rows[-1].update({"status": "not-run", "detail": "dependency did not complete"})
    report = {
        "operations": rows,
        "summary": {
            "status": "fail", "pass": len(rows) - 2, "fail": 1, "notRun": 1,
            "failure": reason,
        },
    }
    monkeypatch.setattr(module, "run_conformance", lambda *_args, **_kwargs: report)
    output = tmp_path / "report.json"
    monkeypatch.setattr(
        module.sys, "argv", ["git_conformance.py", "run", "--output", str(output)]
    )

    assert module.main() == 1

    stderr = capsys.readouterr().err
    assert f"git-conformance: {rows[-2]['id']} failed: {reason}" in stderr
    assert stderr.count(reason) == 1
    assert json.loads(output.read_text(encoding="utf-8")) == report
