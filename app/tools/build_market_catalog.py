def link_list(title: str, manifests: list[dict]) -> list[str]:
    if not manifests:
        return []
    lines = [f'<h2 class="mp-side-title">{escape(title)}</h2>', '<ul class="mp-links">']
    lines.extend(
        f'  <li><a href="{page_url(item["id"])}">{escape(item["name"])}</a></li>'
        for item in manifests
    )
    lines.append("</ul>")
    return lines


