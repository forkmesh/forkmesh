#!/usr/bin/env python3
"""Render the /market package list from the marketplace catalog.

The landing page has to show what the Market actually ships, so the package
cards are generated from ``marketplace/catalog.json`` and the manifests it
points at instead of being retyped by hand. Adding a package to the catalog and
re-running this keeps the public list honest:

    python3 app/tools/build_market_catalog.py

``--check`` reports drift without writing, which is what the test asserts.
"""

from __future__ import annotations

import html
import json
import sys
from pathlib import Path

import site_templates

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "marketplace" / "tools"))

import marketplace_lib  # noqa: E402


REPOSITORY = Path(__file__).resolve().parents[2]
MARKETPLACE = REPOSITORY / "marketplace"
CATALOG = MARKETPLACE / "catalog.json"
PAGE = REPOSITORY / "www" / "templates" / "pages" / "market.html"

START = "<!-- market:catalog:start (generated by app/tools/build_market_catalog.py) -->"
END = "<!-- market:catalog:end -->"
ONBOARDING_START = (
    "<!-- market:onboarding:start (generated by app/tools/build_market_catalog.py) -->"
)
ONBOARDING_END = "<!-- market:onboarding:end -->"
INDENT = " " * 8
APP_URL = "https://app.forkmesh.com"
SOURCE_URL = APP_URL + "/forkmesh/forkmesh/tree/main/marketplace"

# The desktop Market groups the manifest's package type into one of its
# category tabs (MainWindowMarket.cpp). The landing page shows the same
# grouping so a visitor recognizes the shelf a package lands on.
TYPE_LABELS = {
    "extension.native": ("Desktop extension", "Extensions"),
    "extension.vscode": ("IDE extension", "Extensions"),
    "virtual.world": ("World", "Worlds"),
    "virtual.avatar": ("Avatar", "Avatars"),
    "virtual.object": ("3D object", "3D"),
    "virtual.clothing": ("Clothing", "Avatars"),
    "virtual.animation": ("Animation", "3D"),
    "virtual.audio": ("Audio", "Audio"),
    "agent": ("Agent", "AI & Agents"),
    "service.agent": ("Agent service", "Services"),
    "service.development": ("Development service", "Services"),
    "service.design": ("Design service", "Services"),
    "service.hosting": ("Hosting service", "Services"),
    "service.compute": ("Compute service", "Services"),
    "theme": ("Theme", "Themes"),
}

LICENSE_LABELS = {
    "free-open-source": "Free &amp; open source",
    "one-time": "One-time purchase",
    "commercial": "Commercial licence",
    "subscription": "Subscription",
    "pay-what-you-want": "Pay what you want",
    "limited-edition": "Limited edition",
    "free-with-paid-source": "Free, paid source",
    "revenue-share": "Revenue share",
}

ENTRYPOINT_LABELS = {
    "desktop": "Desktop app",
    "world": "World",
    "web": "Web",
    "mobile": "Mobile app",
    "ide": "IDE",
    "theme": "Desktop app",
    "agent": "ForkMesh agent",
    "settings": "Settings",
}

PLACE_LABELS = (("mobile", "Phone"), ("desktop", "Desktop"), ("web", "Web"))


def escape(value) -> str:
    return html.escape(str(value), quote=True)


def load_packages() -> list[dict]:
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    packages = []
    for entry in catalog.get("packages", []):
        relative = entry["manifest"]
        manifest = json.loads((MARKETPLACE / relative).read_text(encoding="utf-8"))
        manifest["_path"] = relative
        packages.append(manifest)
    return packages


def price_label(manifest: dict) -> str:
    price = manifest.get("price") or {}
    amount = price.get("amount") or 0
    if not amount:
        return "Free"
    currency = str(price.get("currency") or "USD")
    formatted = f"{amount:.2f}".rstrip("0").rstrip(".")
    return f"{formatted} {currency}" if currency != "USD" else f"${formatted}"


def runs_in(manifest: dict) -> str:
    hosts = [
        ENTRYPOINT_LABELS.get(key, key.title())
        for key in sorted(manifest.get("entrypoints") or {})
    ]
    return escape(", ".join(hosts)) if hosts else "—"


def shows_on(manifest: dict) -> str:
    install = manifest.get("install") or {}
    if install.get("sync") != "account":
        return ""
    chosen = install.get("places") if isinstance(install.get("places"), list) else []
    labels = [label for place, label in PLACE_LABELS if place in chosen]
    if not labels or len(labels) == len(PLACE_LABELS):
        return "Phone, Desktop and Web; you choose where"
    if len(labels) == 1:
        return labels[0] + " only"
    return " and ".join(labels) + "; you choose where"


def trust_badges(manifest: dict) -> list[str]:
    trust = manifest.get("trust") or {}
    license_block = manifest.get("license") or {}
    badges = []
    if (manifest.get("creator") or {}).get("verified"):
        badges.append("Verified creator")
    if license_block.get("creatorRetainsOwnership"):
        badges.append("Creator retains ownership")
    if trust.get("sourceAvailable"):
        badges.append("Source available")
    if trust.get("reproducibleBuild"):
        badges.append("Reproducible build")
    if trust.get("signature") in {"required", "verified-bundle"}:
        badges.append("Signature verified")
    return badges


MARKET_PREVIEW_ROOT = "/market/previews"


def screenshot_url(directory: str, path: str) -> str:
    return f"{MARKET_PREVIEW_ROOT}/{directory}/{path}"


def market_parent(manifest: dict, ids: set[str]) -> str:
    dependencies = manifest.get("dependencies") or []
    if not dependencies:
        return ""
    parent = dependencies[0].get("id", "")
    return parent if parent in ids and parent != manifest["id"] else ""


def nest_packages(packages: list[dict]) -> list[tuple[dict, list[dict]]]:
    ids = {manifest["id"] for manifest in packages}
    children: dict[str, list[dict]] = {}
    for manifest in packages:
        parent = market_parent(manifest, ids)
        if parent:
            children.setdefault(parent, []).append(manifest)
    return [
        (manifest, children.get(manifest["id"], []))
        for manifest in packages
        if not market_parent(manifest, ids)
    ]


def render_nested(children: list[dict]) -> list[str]:
    lines = [
        '  <details class="market-nested">',
        f"    <summary>Includes {len(children)} package"
        f"{'' if len(children) == 1 else 's'}, added and removed with it</summary>",
        '    <ul class="market-nested-list">',
    ]
    for child in children:
        directory = child["_path"].rsplit("/", 1)[0]
        lines.extend(
            [
                f'      <li class="market-nested-item" data-market-package="{escape(child["id"])}">',
                f"        <strong>{escape(child['name'])}</strong>",
                f'        <span class="market-version">v{escape(child["version"])}</span>',
                f'        <p class="market-summary">{escape(child["summary"])}</p>',
                f'        <a class="market-repository" href="{SOURCE_URL}/{escape(directory)}">'
                "View public repository &nearr;</a>",
                "      </li>",
            ]
        )
    lines.extend(["    </ul>", "  </details>"])
    return lines


def render_card(manifest: dict, children: list[dict] | None = None) -> list[str]:
    type_label, shelf = TYPE_LABELS.get(
        manifest["type"], (manifest["type"], "Extensions")
    )
    creator = manifest.get("creator") or {}
    license_block = manifest.get("license") or {}
    model = LICENSE_LABELS.get(license_block.get("model", ""), "Licensed")
    spdx = license_block.get("spdx")
    permissions = manifest.get("permissions") or []
    screenshots = manifest.get("screenshots") or []
    package_id = manifest["id"]
    directory = manifest["_path"].rsplit("/", 1)[0]

    lines = [
        f'<article class="market-item" data-market-package="{escape(package_id)}"'
        f' data-market-shelf="{escape(shelf)}" data-market-name="{escape(manifest['name'])}">',
        '  <header class="market-item-head">',
        f"    <h3>{escape(manifest['name'])}</h3>",
        f'    <span class="market-version">v{escape(manifest["version"])}</span>',
        "  </header>",
        '  <p class="market-badges">',
        f'    <span class="market-badge">{escape(type_label)}</span>',
        f'    <span class="market-badge market-badge-shelf">{escape(shelf)}</span>',
        f'    <span class="market-badge market-badge-price">{price_label(manifest)}</span>',
        "  </p>",
        # Popularity is filled in from /api/market/installs at view time and
        # stays hidden until a real count arrives, so the page never shows a
        # placeholder number for a package nobody has installed yet.
        f'  <p class="market-stats" data-market-stats="{escape(package_id)}" hidden>',
        '    <span class="market-stat" hidden><strong data-market-downloads>0</strong>'
        " downloads</span>",
        '    <span class="market-stat" hidden><strong data-market-installs>0</strong>'
        " installs</span>",
        '    <span class="market-stat" hidden><strong data-market-people>0</strong>'
        " people use it</span>",
        '    <span class="market-stat" hidden><strong data-market-opens>0</strong>'
        " opens</span>",
        "  </p>",
        # Account ratings (/api/market/reviews/summary) fill the stars in at
        # view time. Rating happens on the package's review page, where a
        # score under five stars requires an improvement review.
        f'  <div class="market-rating" data-market-rating="{escape(package_id)}">',
        '    <span class="market-rating-stars" role="img" aria-label="No ratings yet"'
        ' data-market-rating-stars>',
        '      <span class="market-rating-track" aria-hidden="true">'
        "&#9733;&#9733;&#9733;&#9733;&#9733;</span>",
        '      <span class="market-rating-fill" aria-hidden="true">'
        "&#9733;&#9733;&#9733;&#9733;&#9733;</span>",
        "    </span>",
        '    <span class="market-rating-summary" data-market-rating-summary>No ratings yet</span>',
        f'    <a class="market-rating-link" data-market-rating-link href="{APP_URL}'
        f'/market-reviews?market=forkmesh&amp;package={escape(package_id)}">'
        f'Rate &amp; review<span class="visually-hidden"> {escape(manifest["name"])}</span></a>',
        "  </div>",
    ]

    if screenshots:
        lines.append('  <div class="market-screenshots">')
        for screenshot in screenshots:
            lines.append(
                f'    <img class="market-screenshot" '
                f'src="{escape(screenshot_url(directory, screenshot["path"]))}" '
                f'alt="{escape(screenshot["alt"])}" loading="lazy" '
                'decoding="async" />'
            )
        lines.append("  </div>")

    lines.extend(
        [
            f"  <p class=\"market-summary\">{escape(manifest['summary'])}</p>",
            '  <dl class="market-facts">',
            "    <dt>Creator</dt>",
            f'    <dd><a href="/@{escape(creator.get("handle", ""))}">'
            f"{escape(creator.get('displayName', ''))}</a></dd>",
            "    <dt>Licence</dt>",
            f"    <dd>{model}{f' · {escape(spdx)}' if spdx else ''}</dd>",
            "    <dt>Runs in</dt>",
            f"    <dd>{runs_in(manifest)}</dd>",
        ]
    )
    places = shows_on(manifest)
    if places:
        lines.extend(["    <dt>Shows on</dt>", f"    <dd>{escape(places)}</dd>"])
    lines.append("  </dl>")

    if permissions:
        lines.append('  <p class="market-perm-title">Asks for</p>')
        lines.append('  <ul class="market-perms">')
        for permission in permissions:
            lines.append(
                f'    <li data-risk="{escape(permission["risk"])}">'
                f"{escape(permission['label'])}"
                f'<span class="market-risk">{escape(permission["risk"])}</span></li>'
            )
        lines.append("  </ul>")

    badges = trust_badges(manifest)
    if badges:
        lines.append('  <p class="market-trust">')
        for badge in badges:
            lines.append(f'    <span>{escape(badge)}</span>')
        lines.append("  </p>")

    if children:
        lines.extend(render_nested(children))

    lines.extend(
        [
            f'  <a class="market-repository" href="{SOURCE_URL}/{escape(directory)}">'
            "View public repository &nearr;</a>",
            f'  <a class="market-source" href="{SOURCE_URL}/{escape(directory)}/manifest.json">'
            "Read the manifest &rarr;</a>",
            "</article>",
        ]
    )
    return lines


def render_catalog() -> str:
    lines = [INDENT + START]
    for manifest, children in nest_packages(load_packages()):
        lines.extend(INDENT + line for line in render_card(manifest, children))
    lines.append(INDENT + END)
    return "\n".join(lines)


def installable(manifest: dict) -> bool:
    entrypoints = manifest.get("entrypoints") or {}
    install = manifest.get("install") or {}
    return (
        "theme" in entrypoints
        or "desktop" in entrypoints
        or install.get("sync") == "account"
    )


def pack_members(pack: dict, packages: list[dict]) -> list[dict]:
    by_id = {manifest["id"]: manifest for manifest in packages}
    ids = set(by_id)
    bundleable = [
        manifest for manifest in packages
        if installable(manifest) and manifest["type"] not in ("agent", "theme")
    ]
    if pack["packages"] == "*":
        return [manifest for manifest in bundleable if not market_parent(manifest, ids)]
    allowed = {manifest["id"] for manifest in bundleable}
    return [by_id[item] for item in pack["packages"] if item in allowed]


def render_pack(pack: dict, packages: list[dict]) -> list[str]:
    members = pack_members(pack, packages)
    names = ", ".join(escape(manifest["name"]) for manifest in members)
    lead = "Includes all" if pack["packages"] == "*" else "Includes"
    return [
        f'<article class="market-pack" data-market-pack="{escape(pack["id"])}">',
        f"  <h3>{escape(pack['name'])}</h3>",
        f'  <p class="market-pack-tagline">{escape(pack["tagline"])}</p>',
        f"  <p>{escape(pack['summary'])}</p>",
        f'  <p class="market-pack-includes">{lead} {len(members)} packages: {names}</p>',
        "</article>",
    ]


def render_guide(guide: dict, packs: dict[str, dict], packages: list[dict]) -> list[str]:
    by_id = {manifest["id"]: manifest for manifest in packages}
    pack = packs.get(guide["pack"])
    uses = []
    if pack:
        uses.append(f"the {escape(pack['name'])} pack")
    uses.extend(escape(by_id[item]["name"]) for item in guide["packages"])
    lines = [
        f'<article class="market-guide" data-market-guide="{escape(guide["id"])}">',
        f"  <h3>{escape(guide['title'])}</h3>",
        f'  <span class="market-guide-from">From {escape(guide["from"])}</span>',
        f"  <p>{escape(guide['summary'])}</p>",
        "  <ol>",
    ]
    lines.extend(f"    <li>{escape(step)}</li>" for step in guide["steps"])
    lines.extend(["  </ol>", f"  <p>Uses {' and '.join(uses)}.</p>"])
    if guide["links"]:
        lines.append('  <p class="market-guide-links">')
        lines.extend(
            f'    <a href="{escape(link["url"])}" rel="noopener">{escape(link["label"])} &nearr;</a>'
            for link in guide["links"]
        )
        lines.append("  </p>")
    lines.append("</article>")
    return lines


def render_onboarding() -> str:
    packages = load_packages()
    catalog = marketplace_lib.load_catalog(CATALOG, validate_packages=False)
    packs, guides = marketplace_lib.load_onboarding(catalog)
    lines = [INDENT + ONBOARDING_START]
    body: list[str] = []
    if packs:
        body.extend([
            '<section id="packs" class="market-section">',
            "  <h2>Packs</h2>",
            '  <p class="market-section-lede">',
            "    A pack installs several packages at once. Open the desktop app,",
            "    choose <strong>Market</strong>, then <strong>Packs</strong>, and",
            "    install the whole set with one click.",
            "  </p>",
            '  <div class="market-grid">',
        ])
        for pack in packs:
            body.extend("    " + line for line in render_pack(pack, packages))
        body.extend(["  </div>", "</section>"])
    if guides:
        by_pack = {pack["id"]: pack for pack in packs}
        body.extend([
            '<section id="guides" class="market-section">',
            "  <h2>Moving to ForkMesh</h2>",
            '  <p class="market-section-lede">',
            "    Step-by-step guides for bringing a site's repository, reviews and",
            "    deploys to ForkMesh while your current host keeps serving it. The",
            "    desktop app's <strong>Market</strong>, <strong>Guides</strong> tab",
            "    installs what each guide needs in one click.",
            "  </p>",
            '  <div class="market-grid">',
        ])
        for guide in guides:
            body.extend("    " + line for line in render_guide(guide, by_pack, packages))
        body.extend(["  </div>", "</section>"])
    lines.extend(INDENT + line for line in body)
    lines.append(INDENT + ONBOARDING_END)
    return "\n".join(lines)


def rewrite(source: str) -> str:
    start = source.index(START) - len(INDENT)
    end = source.index(END) + len(END)
    source = source[:start] + render_catalog() + source[end:]
    start = source.index(ONBOARDING_START) - len(INDENT)
    end = source.index(ONBOARDING_END) + len(ONBOARDING_END)
    return source[:start] + render_onboarding() + source[end:]


def main(arguments: list[str]) -> int:
    source = PAGE.read_text(encoding="utf-8")
    if any(marker not in source for marker in (START, END, ONBOARDING_START, ONBOARDING_END)):
        print(f"{PAGE.name} is missing the market catalog markers", file=sys.stderr)
        return 2
    updated = rewrite(source)
    if "--check" in arguments:
        if updated != source:
            print(
                "www/templates/pages/market.html is out of date with marketplace/catalog.json; "
                "run python3 app/tools/build_market_catalog.py",
                file=sys.stderr,
            )
            return 1
        print("market catalog up to date")
        return 0
    if updated != source:
        PAGE.write_text(updated, encoding="utf-8")
        print(f"rewrote {PAGE.relative_to(REPOSITORY)}")
        for path in site_templates.write_pages():
            print(f"rendered {path.relative_to(REPOSITORY)}")
    else:
        print("market catalog up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
