#!/usr/bin/env python3
"""Regenerate the monospace glyph atlases embedded in src/og_card.py.

The repository share card is drawn as a terminal window, in a real
monospace face rather than the 5x7 bitmap font the other cards use. The
Pyodide worker cannot rasterise a TrueType font (it has no Pillow and no
FreeType), so the glyphs are rasterised here, at authoring time, into 8-bit
coverage atlases that og_card.py blends in with row-slice writes.

The face is Geist Mono (SIL Open Font License 1.1; the licence ships next to
it as desktop/resources/fonts/Geist-OFL.txt). Run after changing the sizes
or the glyph set:

    python3 tools/embed_og_mono_font.py      # needs Pillow

Each atlas is every glyph of og_card.MONO_GLYPHS, one fixed cell after the
other (cell rows top to bottom), zlib-compressed and base64-encoded, spliced
between the generated-block markers in og_card.py.
"""

import base64
import re
import sys
import zlib
from pathlib import Path

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:  # pragma: no cover - authoring tool only
    sys.exit("embed_og_mono_font.py needs Pillow (pip install pillow)")

APP = Path(__file__).resolve().parents[1]
FONTS = APP.parent / "desktop" / "resources" / "fonts"
OG_CARD = APP / "src" / "og_card.py"
BEGIN = "# --- generated by tools/embed_og_mono_font.py (do not edit) ---\n"
END = "# --- end of generated mono font ---\n"
# name -> (file, pixel size). Geist Mono advances 0.6 em, so sizes that are
# multiples of 5 keep every cell a whole number of pixels wide.
FACES = (
    ("r20", "GeistMono-Regular.ttf", 20),
    ("r35", "GeistMono-Regular.ttf", 35),
    ("b35", "GeistMono-SemiBold.ttf", 35),
)
BLOCK = "\u2588"


def glyphs_from_source(src):
    match = re.search(r'^MONO_GLYPHS = (.+)$', src, re.M)
    if not match:
        sys.exit("MONO_GLYPHS missing from %s" % OG_CARD)
    return eval(match.group(1), {"chr": chr, "range": range})  # noqa: S307


def atlas(path, size, glyphs):
    font = ImageFont.truetype(str(path), size)
    ascent, descent = font.getmetrics()
    advance = font.getlength("M")
    cell_w = int(round(advance))
    assert abs(advance - cell_w) < 0.01, (path.name, size, advance)
    cell_h = ascent + descent
    raw = bytearray()
    for ch in glyphs:
        image = Image.new("L", (cell_w, cell_h), 0)
        draw = ImageDraw.Draw(image)
        if ch == BLOCK:
            draw.rectangle([0, 0, cell_w - 1, cell_h - 1], fill=255)
        else:
            draw.text((0, 0), ch, font=font, fill=255)
        raw += image.tobytes()
    blob = base64.b64encode(zlib.compress(bytes(raw), 9)).decode("ascii")
    return cell_w, cell_h, ascent, blob


def main():
    src = OG_CARD.read_text(encoding="utf-8")
    glyphs = glyphs_from_source(src)
    out = [BEGIN, "_MONO_FONTS = {\n"]
    for name, filename, size in FACES:
        cell_w, cell_h, ascent, blob = atlas(FONTS / filename, size, glyphs)
        lines = "\n".join('        "%s"' % blob[i:i + 72]
                          for i in range(0, len(blob), 72))
        out.append('    # %s %dpx\n    "%s": (%d, %d, %d, (\n%s\n    )),\n'
                   % (filename[:-4], size, name, cell_w, cell_h, ascent,
                      lines))
    out.append("}\n" + END)
    block = "".join(out)
    start = src.find(BEGIN)
    stop = src.find(END)
    if start < 0 or stop < start:
        sys.exit("generated-block markers missing from %s" % OG_CARD)
    OG_CARD.write_text(src[:start] + block + src[stop + len(END):],
                       encoding="utf-8")
    print("wrote %d font atlases into %s" % (len(FACES), OG_CARD))


if __name__ == "__main__":
    main()
