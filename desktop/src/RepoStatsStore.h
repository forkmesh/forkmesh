#pragma once

#include <QByteArray>
#include <QJsonObject>
#include <QString>
#include <QVector>

struct RepoStatsSample {
    QString day;
    qint64 bytes = 0;
    qint64 lines = 0;
    qint64 files = 0;
};

// Ratchet Mode as the repository's local Git config records it: whether it
// is on, and the size ceiling commits are checked against (set on the day it
// was armed and refreshed each day the repository is measured).
struct RepoRatchetReading {
    bool enabled = false;
    qint64 ceilingBytes = 0;
    QString ceilingDay;
};

class RepoStatsStore
{
public:
    static QVector<RepoStatsSample> captureDaily(const QString &repoDir,
                                                 QString *error = nullptr);
    static QVector<RepoStatsSample> load(const QString &repoDir,
                                         QString *error = nullptr);
    static bool repositoryJsonEnabled(const QString &repoDir);
    static bool setRepositoryJsonEnabled(const QString &repoDir, bool enabled,
                                         QString *error = nullptr);
    static bool ratchetEnabled(const QString &repoDir);
    // Reads the config only (a few git invocations, no tree measurement), so
    // a dashboard can poll it off the GUI thread.
    static RepoRatchetReading ratchetReading(const QString &repoDir);
    static bool setRatchetEnabled(const QString &repoDir, bool enabled,
                                  QString *error = nullptr);
    static bool stagedCommitAllowed(const QString &repoDir, QString *reason);
    static QString agentGuidance(const QString &repoDir);
    // Repository statistics are generated by ForkMesh in the primary
    // checkout. Callers that only need a clean tree for Git plumbing may
    // preserve this exact known file while still rejecting every user edit.
    static bool onlyGeneratedStatsDirty(const QByteArray &porcelainStatus);

private:
    static RepoStatsSample measure(const QString &repoDir, QString *error);
    static QVector<RepoStatsSample> backfill(const QString &repoDir,
                                             const RepoStatsSample &today);
    static qint64 ceilingBytes(const QString &repoDir, const RepoStatsSample &now,
                               bool refreshStaleDay);
    static QString statsPath(const QString &repoDir);
};
